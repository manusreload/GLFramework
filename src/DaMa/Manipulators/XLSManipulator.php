namespace GLFramework\DaMa\Manipulators;

use PhpOffice\PhpSpreadsheet\IOFactory;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;

/**
 * Class XLSManipulator
 *
 * Lee ficheros Excel 97/2003 (.xls) con PhpSpreadsheet. El lector anterior
 * (nuovo/spreadsheet-reader + php-excel-reader) usa constructores estilo PHP 4
 * y no funciona en PHP 8.
 *
 * @package GLFramework\DaMa\Manipulators
 */
class XLSManipulator extends ManipulatorCore
{

    /**
     * @var Spreadsheet
     */
    var $reader;

    /**
     * @var Worksheet
     */
    private $sheet;
    protected $readerType = 'Xls';
    private $row = 1;
    private $highestRow = 0;
    private $highestColumn = 'A';

    /**
     * TODO
     *
     * @param $file
     * @param array $config
     */
    public function open($file, $config = array())
    {
        $reader = IOFactory::createReader($this->readerType);
        $this->reader = $reader->load($file);
        $this->changeSheet(0);
    }

    /**
     * TODO
     *
     * @return array|bool
     */
    public function next()
    {
        if ($this->row > $this->highestRow) {
            return false;
        }
        $range = 'A' . $this->row . ':' . $this->highestColumn . $this->row;
        $this->row++;
        $values = $this->sheet->rangeToArray($range, '', true, true, false);
        return array_map(array($this, 'map'), $values[0]);
    }

    /**
     * TODO
     *
     * @param $index
     */
    public function setSheet($index)
    {
        $this->changeSheet($index);
        parent::setSheet($index); // TODO: Change the autogenerated stub
    }

    /**
     * TODO
     *
     * @param $index
     */
    private function changeSheet($index)
    {
        $this->sheet = $this->reader->getSheet($index);
        $this->row = 1;
        $this->highestRow = $this->sheet->getHighestDataRow();
        $this->highestColumn = $this->sheet->getHighestDataColumn();
    }

    /**
     * TODO
     *
     * @param $item
     * @return string
     */
    public function map($item)
    {
        return trim((string)$item);
    }
}
